#!/usr/bin/python3
# Generate s5kgd1-regs.h from LG's CamX sensormodule binary (front S5KGD1).
import sys
sys.path.insert(0, '/Users/hellonfire/Coding/nura/out/camtools')
import chromatix as c
src, dst = sys.argv[1], sys.argv[2]
PFX = sys.argv[3] if len(sys.argv) > 3 else 's5kgd1'
d, n = c.load(src)
rs = list(c.regsettings(d, n))
byid = {nid: recs for _, nid, recs in rs}
INIT, MODE1 = (int(sys.argv[4], 0), int(sys.argv[5], 0)) if len(sys.argv) > 5 else (0x26a3, 0x7c1)
def emit(name, recs):
    out = ['static const struct cam_reg %s[] = {' % name]
    for a, vs, at, dt, dl in recs:
        assert at == 2 and dt == 2, (hex(a), at, dt)
        for v in vs:
            out.append('\t{ 0x%04x, 0x%04x, %d },' % (a, v, dl))
            dl = 0
    out.append('};')
    return '\n'.join(out)
h = ['/* Generated by out/camtools/gen_s5kgd1.py from LG G8x vendor',
     ' * ' + src.split('/')[-1] + ' (CamX). 16-bit addr/data;',
     ' * third column is a delay in microseconds after the write. */',
     emit(PFX + '_init_regs', byid[INIT]), '',
     emit(PFX + '_mode_regs', byid[MODE1]), '']
open(dst, 'w').write('\n'.join(h))
delays = [(hex(a), dl) for a, vs, _, _, dl in byid[INIT] + byid[MODE1] if dl]
print('init', len(byid[INIT]), 'mode', len(byid[MODE1]), 'delays', delays[:10])
m = {}
for a, vs, *_ in byid[MODE1]:
    if a < 0x6000: m[a] = vs[0]
print({hex(k): hex(v) for k, v in sorted(m.items())})
